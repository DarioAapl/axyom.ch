"""Rebuild privacy.html from the PUBLISHED Termly privacy policy.

WHY A STATIC COPY AND NOT TERMLY'S EMBED SCRIPT
-----------------------------------------------
The embed loads an iframe from app.termly.io on every visit. That is a third
party (and possibly cookies) on the one page that tells visitors this site uses
neither. The policy HTML Termly returns is self-contained (no scripts, no
images), so we copy it in verbatim and serve it ourselves.

The text is maintained in Termly (website "Axyom", policy fbf60a23-…), not
here. After you publish a change in Termly, run:

    python3 _tools/sync_privacy.py

then review the diff and commit. Lives in _tools/ because Jekyll does not
publish underscore folders.
"""
import json
import pathlib
import re
import sys
import urllib.request

POLICY = "fbf60a23-a155-487c-b875-5083d5dbc018"
URL = f"https://app.termly.io/api/v1/consumer/policies/{POLICY}/content?lang=en"
OUT = pathlib.Path(__file__).resolve().parents[1] / "privacy.html"

HEAD = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Privacy Policy — Axyom AI</title>
<meta name="description" content="What Axyom AI collects, why, who processes it, and how long it is kept. Covers the website, the Shopify app and the storefront assistant." />
<meta name="theme-color" content="#ffffff" />
<meta name="color-scheme" content="light" />
<link rel="canonical" href="https://axyom.ch/privacy.html" />
<meta name="robots" content="index,follow" />
<style>
  html, body { background: #ffffff; color: #1a1a1a; margin: 0; }
  .legal { max-width: 46rem; margin: 0 auto; padding: 3rem 16px 6rem; overflow-wrap: anywhere; }
  .legal .back { display: inline-block; margin-bottom: 2rem; font: 15px/1.4 Arial, sans-serif; color: #1C5C87; }
  .legal table { display: block; overflow-x: auto; max-width: 100%; }
  .legal p, .legal li, .legal div { line-height: 1.6; }
</style>
</head>
<body>
<main class="legal">
<a class="back" href="/">&larr; Axyom AI</a>
<!-- Generated by _tools/sync_privacy.py from the published Termly policy
     __POLICY__. Do not edit by hand: change it in Termly, publish, re-run. -->
"""

TAIL = """
</main>
</body>
</html>
"""


def main() -> int:
    # Termly's edge refuses Python's default User-Agent with a 403.
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0 axyom-privacy-sync"})
    with urllib.request.urlopen(req, timeout=30) as r:
        content = json.load(r)["content"]
    if "PRIVACY POLICY" not in content or len(content) < 50_000:
        print("refusing: response does not look like the policy", file=sys.stderr)
        return 1
    if re.search(r"<script|<iframe|<img", content, re.I):
        print("refusing: policy HTML now contains scripts/iframes/images", file=sys.stderr)
        return 1
    OUT.write_text(HEAD.replace("__POLICY__", POLICY) + content + TAIL, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
