  function pick() {
    var q = /[?&]lang=(en|de)\b/.exec(location.search);
    if (q) return q[1];
    try { var s = localStorage.getItem(KEY); if (s === 'en' || s === 'de') return s; } catch (e) {}
    return /^de\b/i.test(navigator.language || '') ? 'de' : 'en';
  }

  var lang = pick();
  document.documentElement.lang = lang;

  // Lookup for strings the page script builds itself; German fallback is passed in.
  window.axyomT = function (key, de) { return lang === 'en' && EN[key] != null ? EN[key] : de; };
  window.axyomLang = lang;

  if (lang === 'en') {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = EN[el.getAttribute('data-i18n')]; if (v != null) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var v = EN[el.getAttribute('data-i18n-html')]; if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':'), v = EN[p[1]]; if (v != null) el.setAttribute(p[0], v);
      });
    });
    if (EN[document.documentElement.getAttribute('data-i18n-title')]) {
      document.title = EN[document.documentElement.getAttribute('data-i18n-title')];
    }
  }

  document.querySelectorAll('.lang-switch button').forEach(function (b) {
    var on = b.getAttribute('data-lang') === lang;
    b.setAttribute('aria-pressed', on ? 'true' : 'false');
    b.addEventListener('click', function () {
      if (on) return;
      var to = b.getAttribute('data-lang');
      try { localStorage.setItem(KEY, to); } catch (e) {}
      // ?lang= as well, so the switch works even where storage is blocked.
      location.href = location.pathname + '?lang=' + to;
    });
  });
